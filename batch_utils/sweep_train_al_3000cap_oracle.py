#!/usr/bin/env python
"""
Oracle/clean baseline complement to the train_al 3000-oracle-cost-cap sweep
(sweep_train_al_3000cap.py, job 30813471). That sweep only sent the NOISY arm
(--tau {0.1,0.25,0.5}); there was no clean reference to compare against.

This adds the missing oracle arm: a perfect annotator (no label noise) via
--target_nu 0.0 (tau->1, nu'->0), matching how the 4_15 oracle-vs-noisy sweep
launched its clean runs. Existing oracle runs in output/ only reached B=100 /
max_iter=10 (1200 oracle-cost) on seeds {1,2,3}, so they can't span this graph;
these run to the full 3000 cap across all three batch sizes on seeds {2,3,4}.

Grid (18 jobs):
  strategies : probcover, random
  seeds      : 2, 3, 4
  (batch, max_iter): (100,29), (300,9), (1000,2)   -> oracle-cost = (1+max_iter)*batch = 3000

No --tau / --nu_prime (oracle has neither). All other args identical to the
noisy sweep (--initial_delta 0.75 --eval_model_type from_features, RESNET18,
initial_size=0). Reuses the SAME --sweep-name as the noisy sweep so the clean
curves land in the same dashboard graph selection (the Graphs tab filters by
sweep_name).

Usage:
    python batch_utils/sweep_train_al_3000cap_oracle.py            # dry-run
    python batch_utils/sweep_train_al_3000cap_oracle.py --submit   # sbatch via phoenix-gw
"""
from __future__ import annotations
import sys, subprocess, argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sweep_train_al import (
    REPO_DIR, TRAIN_SCRIPT, LOG_DIR, VENV_ACTIVATE, SLURM_OPTS,
    SLURM_LOGIN_NODE, SBATCH_BIN, SLURM_CONF,
)

CFG = "deep_al/configs/cifar100/al/RESNET18.yaml"
GENERATED = REPO_DIR / "batch_utils" / "_generated_sweep_train_al_3000cap_oracle.sh"
THROTTLE = 6

# Reuse the noisy sweep's name so the clean runs appear alongside it in the
# dashboard Graphs tab (selection filters on sweep_name, not sweep_id).
SWEEP_NAME = "train_al_3000cap_pcrand__20260611_131458"

STRATEGIES = ["probcover", "random"]
SEEDS = [2, 3, 4]
COMBOS = [(100, 29), (300, 9), (1000, 2)]  # (batch, max_iter)


def build_jobs() -> list[str]:
    jobs = []
    for strat in STRATEGIES:
        for batch, max_iter in COMBOS:
            for seed in SEEDS:
                exp = f"{strat}_B{batch}_oracle_seed{seed}"
                cmd = (
                    f"python {TRAIN_SCRIPT} --initial_delta 0.75 --budget {batch} "
                    f"--eval_model_type from_features --max_iter {max_iter} "
                    f"--cfg {CFG} --target_nu 0.0 --al {strat} --seed {seed} "
                    f"--exp-name {exp} --sweep-name {SWEEP_NAME} "
                    f"--track_progress"
                )
                jobs.append(cmd)
    return jobs


def build_script(jobs: list[str]) -> str:
    n = len(jobs)
    job_lines = "\n".join(f'JOBS[{i}]="{jobs[i]}"' for i in range(n))
    header = "\n".join(f"#SBATCH --{k}={v}" for k, v in SLURM_OPTS.items())
    return (
        f"#!/bin/bash\n"
        f"#SBATCH --array=0-{n - 1}%{THROTTLE}\n"
        f"{header}\n\n"
        f"# ---- job table (auto-generated by sweep_train_al_3000cap_oracle.py) ----\n"
        f"declare -A JOBS\n{job_lines}\n\n"
        f"CMD=${{JOBS[$SLURM_ARRAY_TASK_ID]}}\n"
        f'echo "Task $SLURM_ARRAY_TASK_ID: $CMD"\n\n'
        f"cd {REPO_DIR}\n"
        f"source {VENV_ACTIVATE}\n"
        f'eval "$CMD"\n'
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--submit", action="store_true",
                    help="Write the .sh and submit via sbatch on phoenix-gw")
    args = ap.parse_args()

    jobs = build_jobs()
    print(f"sweep_name (reused): {SWEEP_NAME}")
    print(f"total jobs: {len(jobs)}  (array throttle %{THROTTLE})\n")
    print("all jobs:")
    for c in jobs:
        print("  " + c.split(str(TRAIN_SCRIPT))[1].strip())

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(build_script(jobs))
    print(f"\nwritten: {GENERATED}")

    if not args.submit:
        print("\nDry-run. Re-run with --submit to sbatch via phoenix-gw.")
        return

    submit_cmd = f"SLURM_CONF={SLURM_CONF} {SBATCH_BIN} {GENERATED}"
    res = subprocess.run(["ssh", SLURM_LOGIN_NODE, submit_cmd], capture_output=True, text=True)
    if res.returncode == 0:
        print(f"Submitted: {res.stdout.strip()}")
    else:
        print(f"ERROR: {res.stderr.strip()}")


if __name__ == "__main__":
    main()
