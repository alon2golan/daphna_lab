"""
Launch the AUM-filter ablation sweep (CIFAR100, framework-2 linear-on-features).

Grid:
  noise levels {20, 50, 80}% symmetric
    x  filter_before_train {True, False}        (NOISE_FILTER.TRAIN_ON_CLEAN)
    x  AL method {npc, probcover, random}
    x  seed {1, 2, 3}
  = 3 x 2 x 3 x 3 = 54 runs.  b = 100 per round, 29 rounds (labeled set 100 -> 3000).

The noise level AND the filter_before_train arm are encoded in the --cfg file
(AUMFILTER_n{20,50,80}_clean{on,off}.yaml); al and seed are CLI args. All cells
keep NOISE_FILTER.METHOD='aum' so the only knob varying between the two arms is
TRAIN_ON_CLEAN. The sweep-name carries an "AUMFILTER" token so the dashboard
auto-categorises every run as "aum_filter".

Mirrors launch_netta_npc_sweep.py: reuses sweep_train_al.build_jobs_from for the
job commands but writes its own throttled (%N) sbatch array script and submits
via ssh to the SLURM login node.

Usage:
    python batch_utils/launch_aum_filter_sweep.py            # dry-run: print plan + script
    python batch_utils/launch_aum_filter_sweep.py --submit   # write .sh and sbatch it
"""
import argparse
import subprocess
from datetime import datetime
from pathlib import Path

from sweep_train_al import (
    build_jobs_from,
    SLURM_OPTS,
    SLURM_LOGIN_NODE,
    SBATCH_BIN,
    SLURM_CONF,
    REPO_DIR,
    VENV_ACTIVATE,
    LOG_DIR,
)

# --- sweep definition --------------------------------------------------------
CFG_DIR = "deep_al/configs/cifar100/al"
AL_CONFIGS = [
    f"--cfg {CFG_DIR}/AUMFILTER_n20_cleanon.yaml",
    f"--cfg {CFG_DIR}/AUMFILTER_n20_cleanoff.yaml",
    f"--cfg {CFG_DIR}/AUMFILTER_n50_cleanon.yaml",
    f"--cfg {CFG_DIR}/AUMFILTER_n50_cleanoff.yaml",
    f"--cfg {CFG_DIR}/AUMFILTER_n80_cleanon.yaml",
    f"--cfg {CFG_DIR}/AUMFILTER_n80_cleanoff.yaml",
]
GRID = dict(
    al=["npc", "probcover", "random"],
    seed=[1, 2, 3],
)
FIXED_ARGS = (
    "--eval_model_type from_features "
    "--budget 100 "
    "--initial_delta 0.75 "
    "--max_iter 29 "          # 100 -> 3000 labeled set (30 episodes)
)

ARRAY_THROTTLE = 6  # max concurrent array tasks (%N) — keep within group GPU quota
SWEEP_SCRIPT = Path(__file__).resolve().parent / "_aum_filter_sweep.sh"


def build_script(jobs, array_throttle):
    n = len(jobs)
    job_lines = "\n".join(f'JOBS[{i}]="{jobs[i]}"' for i in range(n))
    header_lines = "\n".join(f"#SBATCH --{k}={v}" for k, v in SLURM_OPTS.items())
    return (
        f"#!/bin/bash\n"
        f"#SBATCH --array=0-{n - 1}%{array_throttle}\n"
        f"{header_lines}\n"
        f"\n"
        f"# ---- job table (auto-generated by launch_aum_filter_sweep.py) ----\n"
        f"declare -A JOBS\n"
        f"{job_lines}\n"
        f"\n"
        f"CMD=${{JOBS[$SLURM_ARRAY_TASK_ID]}}\n"
        f'echo "Task $SLURM_ARRAY_TASK_ID: $CMD"\n'
        f"\n"
        f"cd {REPO_DIR}\n"
        f"source {VENV_ACTIVATE}\n"
        f'eval "$CMD"\n'
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--submit", action="store_true",
                    help="Write the .sh and sbatch it via the SLURM login node.")
    args = ap.parse_args()

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    sweep_name = f"AUMFILTER_clean_ablation_cifar100_n20_50_80__{ts}"
    jobs = build_jobs_from(AL_CONFIGS, GRID, FIXED_ARGS, sweep_name=sweep_name)
    script = build_script(jobs, ARRAY_THROTTLE)

    print(f"Sweep name : {sweep_name}")
    print(f"Cfgs       : {len(AL_CONFIGS)}  (noise 20/50/80 × filter on/off)")
    print(f"Grid       : {GRID}")
    print(f"Fixed args : {FIXED_ARGS.strip()}")
    print(f"Total runs : {len(jobs)}  (array 0-{len(jobs) - 1}%{ARRAY_THROTTLE})\n")
    for j in jobs:
        print("  " + j.replace(str(REPO_DIR) + "/", ""))

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    SWEEP_SCRIPT.write_text(script)
    print(f"\nWritten: {SWEEP_SCRIPT}")

    if not args.submit:
        print("\nDry-run. Re-run with --submit to launch.")
        return

    submit_cmd = f"SLURM_CONF={SLURM_CONF} {SBATCH_BIN} {SWEEP_SCRIPT}"
    ssh_cmd = ["ssh", SLURM_LOGIN_NODE, submit_cmd]
    print(f"\nSubmitting: {' '.join(ssh_cmd)}")
    result = subprocess.run(ssh_cmd, capture_output=True, text=True)
    if result.returncode == 0:
        print(f"Submitted: {result.stdout.strip()}")
    else:
        print(f"ERROR (rc={result.returncode}): {result.stderr.strip()}")


if __name__ == "__main__":
    main()
