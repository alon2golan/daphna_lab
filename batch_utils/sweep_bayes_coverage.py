"""
Launch the Bayesian-coverage method comparison (design doc §9 D — the
product-vs-additive gate + core hypothesis vs probcover).

Grid (CIFAR10 first — cheap, C=10; CIFAR100 is a later stress run):
  noise levels {0.0, 0.2, 0.5, 0.8} symmetric   (one --cfg per level)
    x  AL method {random, probcover, bayes_additive, bayes_product}
    x  seed {1, 2, 3}
  = 4 x 4 x 3 = 48 runs.  budget 100 per round, 10 episodes -> up to 1000 labeled.

Arms and why this exact set:
  * random          — floor.
  * probcover       — non-noise-aware coverage baseline.
  * bayes_additive  — BayesianCoverage COMBINE=additive == Itai's rule
                      (the reproduction control).
  * bayes_product   — BayesianCoverage COMBINE=product == our proposed math.
  npc is deliberately EXCLUDED here: it structurally requires a noise filter
  (NOISE_FILTER.METHOD=aum), which auto-enables training-side clean-filtering and
  would confound this comparison, where every arm trains on the raw observed
  (noisy) labels. All BAYESCOV_n*.yaml set METHOD='none'. npc is added as a
  follow-up arm (with its filter, a documented asymmetry) once this gate passes.

Decision rules this sweep feeds (design §9 D):
  * sanity      : at noise 0.0 all four arms within noise of each other.
  * Itai repro  : bayes_additive tracks probcover at noise 0.0.
  * core hyp    : bayes_product beats probcover at noise >= 0.2.
  * THE GATE    : adopt COMBINE=product as default ONLY if bayes_product >=
                  bayes_additive across the grid with a real win at >= one noise
                  level; else keep additive and record why.

Each --cfg carries a `--tag noise=<level>`; the AL method (the arm, incl. the
combine rule for the bayes_* arms) is the `--al` grid value, so the dashboard
Comparison tab facets cleanly. The sweep-name carries a "BAYESCOV" token for
auto-categorisation. --track_progress marks every run for the Comparison tab.

Mirrors launch_aum_filter_sweep.py.

Usage:
    python batch_utils/sweep_bayes_coverage.py            # dry-run: print plan + script
    python batch_utils/sweep_bayes_coverage.py --submit   # write .sh and sbatch it
"""
import argparse
import subprocess
from datetime import datetime
from pathlib import Path

from sweep_train_al import (
    build_jobs_from,
    SLURM_OPTS,
    SLURM_LOGIN_NODE,
    SBATCH_BIN,
    SLURM_CONF,
    REPO_DIR,
    VENV_ACTIVATE,
    LOG_DIR,
)

# --- sweep definition --------------------------------------------------------
# NOTE on budget regime: budget 100 x10 episodes -> 100..1000 labeled. On CIFAR100
# (C=100) that is 1..10 examples/class = ProbCover's intended LOW-budget regime.
# On CIFAR10 (C=10) the SAME grid reaches 100/class, well past the low-budget
# regime where coverage helps — read CIFAR10 curves only at the low end (<=~300).
DATASET_DIRS = {"cifar10": "deep_al/configs/cifar10/al",
                "cifar100": "deep_al/configs/cifar100/al"}

def al_configs_for(cfg_dir):
    # Each cfg fixes the noise level; the noise=<level> tag makes it a dashboard facet.
    return [
        f"--cfg {cfg_dir}/BAYESCOV_n00.yaml --tag noise=0.0",
        f"--cfg {cfg_dir}/BAYESCOV_n20.yaml --tag noise=0.2",
        f"--cfg {cfg_dir}/BAYESCOV_n50.yaml --tag noise=0.5",
        f"--cfg {cfg_dir}/BAYESCOV_n80.yaml --tag noise=0.8",
    ]
GRID = dict(
    al=["random", "probcover", "bayes_additive", "bayes_product"],
    seed=[1, 2, 3],
)
FIXED_ARGS = (
    "--track_progress "
    "--eval_model_type from_features "
    "--kernel_type tophat "
    "--budget 100 "
    "--initial_delta 0.75 "
    "--max_iter 9 "          # 100 -> 1000 labeled set (10 episodes)
)

ARRAY_THROTTLE = 6  # max concurrent array tasks (%N) — keep within group GPU quota
SWEEP_SCRIPT = Path(__file__).resolve().parent / "_bayes_coverage_sweep.sh"


def build_script(jobs, array_throttle):
    n = len(jobs)
    job_lines = "\n".join(f'JOBS[{i}]="{jobs[i]}"' for i in range(n))
    header_lines = "\n".join(f"#SBATCH --{k}={v}" for k, v in SLURM_OPTS.items())
    return (
        f"#!/bin/bash\n"
        f"#SBATCH --array=0-{n - 1}%{array_throttle}\n"
        f"{header_lines}\n"
        f"\n"
        f"# ---- job table (auto-generated by sweep_bayes_coverage.py) ----\n"
        f"declare -A JOBS\n"
        f"{job_lines}\n"
        f"\n"
        f"CMD=${{JOBS[$SLURM_ARRAY_TASK_ID]}}\n"
        f'echo "Task $SLURM_ARRAY_TASK_ID: $CMD"\n'
        f"\n"
        f"cd {REPO_DIR}\n"
        f"source {VENV_ACTIVATE}\n"
        f'eval "$CMD"\n'
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", choices=sorted(DATASET_DIRS), default="cifar10",
                    help="Which dataset's BAYESCOV_n*.yaml configs to sweep.")
    ap.add_argument("--train_label_modes", default=None,
                    help="Comma-separated §5 TRAIN_LABEL_MODE arms (e.g. "
                         "observed,map_posterior,filtered,soft_posterior,reweighted). "
                         "When set, the sweep FIXES al=bayes_product and varies the "
                         "training-label policy instead of the AL method. Recorded in "
                         "result.json params.train_label_mode (dashboard facet).")
    ap.add_argument("--al", default=None,
                    help="Comma-separated subset of AL arms to run (default: all "
                         "four: random,probcover,bayes_additive,bayes_product). Use "
                         "for a targeted re-run, e.g. --al bayes_additive.")
    ap.add_argument("--submit", action="store_true",
                    help="Write the .sh and sbatch it via the SLURM login node.")
    args = ap.parse_args()

    al_configs = al_configs_for(DATASET_DIRS[args.dataset])
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    if args.train_label_modes:
        modes = [m.strip() for m in args.train_label_modes.split(",") if m.strip()]
        grid = dict(al=["bayes_product"], train_label_mode=modes, seed=[1, 2, 3])
        sweep_name = f"BAYESCOV_trainmode_{args.dataset}_n0_20_50_80__{ts}"
    else:
        grid = dict(GRID)
        if args.al:
            grid["al"] = [a.strip() for a in args.al.split(",") if a.strip()]
        sweep_name = f"BAYESCOV_compare_{args.dataset}_n0_20_50_80__{ts}"
    jobs = build_jobs_from(al_configs, grid, FIXED_ARGS, sweep_name=sweep_name)
    script = build_script(jobs, ARRAY_THROTTLE)

    print(f"Sweep name : {sweep_name}")
    print(f"Dataset    : {args.dataset}")
    print(f"Cfgs       : {len(al_configs)}  (noise 0.0/0.2/0.5/0.8)")
    print(f"Grid       : {grid}")
    print(f"Fixed args : {FIXED_ARGS.strip()}")
    print(f"Total runs : {len(jobs)}  (array 0-{len(jobs) - 1}%{ARRAY_THROTTLE})\n")
    for j in jobs:
        print("  " + j.replace(str(REPO_DIR) + "/", ""))

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    SWEEP_SCRIPT.write_text(script)
    print(f"\nWritten: {SWEEP_SCRIPT}")

    if not args.submit:
        print("\nDry-run. Re-run with --submit to launch "
              "(CHECK GROUP GPU QUOTA FIRST — see daphna_lab/CLAUDE.md).")
        return

    submit_cmd = f"SLURM_CONF={SLURM_CONF} {SBATCH_BIN} {SWEEP_SCRIPT}"
    ssh_cmd = ["ssh", SLURM_LOGIN_NODE, submit_cmd]
    print(f"\nSubmitting: {' '.join(ssh_cmd)}")
    result = subprocess.run(ssh_cmd, capture_output=True, text=True)
    if result.returncode == 0:
        print(f"Submitted: {result.stdout.strip()}")
    else:
        print(f"ERROR (rc={result.returncode}): {result.stderr.strip()}")


if __name__ == "__main__":
    main()
