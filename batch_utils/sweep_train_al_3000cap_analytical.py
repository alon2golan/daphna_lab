#!/usr/bin/env python
"""
Analytical-rule complement to the train_al 3000-oracle-cost-cap sweep
(sweep_train_al_3000cap.py, job 30813471).

That sweep set nu' from the NoAA-estimated nu_prime_cache.json (a different,
empirically-fit noise level per tau). This variant instead uses the
*analytical rule* from Tomer's thesis: the break-even noise is nu' = 1 - tau
(the Fig 5.5 "Analytical (tau = 1 - nu)" boundary: use the noisy annotator
while tau <= 1 - nu, i.e. nu <= 1 - tau), i.e.

    tau=0.1  -> nu'=0.9
    tau=0.25 -> nu'=0.75
    tau=0.5  -> nu'=0.5

nu' is passed EXPLICITLY via --nu_prime (= 1 - tau), so no cache lookup happens
(configure_nu_prime_annotator Case 2 takes the CLI value directly:
NOISE_RATES <- [1-tau], COSTS <- [tau]).

Grid (18 jobs):
  strategies : probcover, random
  taus       : 0.1, 0.25, 0.5
  seeds      : 2, 3, 4
  batch      : 100 only, max_iter=29  -> oracle-cost = (1+29)*100 = 3000

All other args identical to the noisy sweep (--initial_delta 0.75
--eval_model_type from_features, RESNET18, initial_size=0). Reuses the SAME
--sweep-name as the original sweep so the analytical curves land in the same
dashboard Graphs selection (the Graphs tab filters by sweep_name, not sweep_id);
exp-names carry an `analytical` tag so they never collide with the cache-based
or oracle runs.

Usage:
    python batch_utils/sweep_train_al_3000cap_analytical.py            # dry-run
    python batch_utils/sweep_train_al_3000cap_analytical.py --submit   # sbatch via phoenix-gw
"""
from __future__ import annotations
import sys, subprocess, argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sweep_train_al import (
    REPO_DIR, TRAIN_SCRIPT, LOG_DIR, VENV_ACTIVATE, SLURM_OPTS,
    SLURM_LOGIN_NODE, SBATCH_BIN, SLURM_CONF,
)

CFG = "deep_al/configs/cifar100/al/RESNET18.yaml"
GENERATED = REPO_DIR / "batch_utils" / "_generated_sweep_train_al_3000cap_analytical.sh"
THROTTLE = 6

# Reuse the original sweep's name so the analytical runs appear alongside the
# cache-based and oracle curves in the dashboard Graphs tab.
SWEEP_NAME = "train_al_3000cap_pcrand__20260611_131458"

STRATEGIES = ["probcover", "random"]
TAUS = [0.1, 0.25, 0.5]
SEEDS = [2, 3, 4]
BATCH = 100
MAX_ITER = 29  # (1 + 29) * 100 = 3000 oracle-cost cap


def build_jobs() -> list[str]:
    jobs = []
    for strat in STRATEGIES:
        for tau in TAUS:
            nu = round(1 - tau, 10)  # analytical rule: nu' = 1 - tau
            for seed in SEEDS:
                tau_s = str(tau).replace(".", "p")
                exp = f"{strat}_B{BATCH}_analytical_tau{tau_s}_seed{seed}"
                cmd = (
                    f"python {TRAIN_SCRIPT} --initial_delta 0.75 --budget {BATCH} "
                    f"--eval_model_type from_features --max_iter {MAX_ITER} "
                    f"--cfg {CFG} --tau {tau} --nu_prime {nu} --al {strat} --seed {seed} "
                    f"--exp-name {exp} --sweep-name {SWEEP_NAME} "
                    f"--track_progress --tag nu_tag=nu_analytical"
                )
                jobs.append(cmd)
    return jobs


def build_script(jobs: list[str]) -> str:
    n = len(jobs)
    job_lines = "\n".join(f'JOBS[{i}]="{jobs[i]}"' for i in range(n))
    header = "\n".join(f"#SBATCH --{k}={v}" for k, v in SLURM_OPTS.items())
    return (
        f"#!/bin/bash\n"
        f"#SBATCH --array=0-{n - 1}%{THROTTLE}\n"
        f"{header}\n\n"
        f"# ---- job table (auto-generated by sweep_train_al_3000cap_analytical.py) ----\n"
        f"declare -A JOBS\n{job_lines}\n\n"
        f"CMD=${{JOBS[$SLURM_ARRAY_TASK_ID]}}\n"
        f'echo "Task $SLURM_ARRAY_TASK_ID: $CMD"\n\n'
        f"cd {REPO_DIR}\n"
        f"source {VENV_ACTIVATE}\n"
        f'eval "$CMD"\n'
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--submit", action="store_true",
                    help="Write the .sh and submit via sbatch on phoenix-gw")
    args = ap.parse_args()

    jobs = build_jobs()
    print(f"sweep_name (reused): {SWEEP_NAME}")
    print(f"total jobs: {len(jobs)}  (array throttle %{THROTTLE})\n")
    print("all jobs:")
    for c in jobs:
        print("  " + c.split(str(TRAIN_SCRIPT))[1].strip())

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(build_script(jobs))
    print(f"\nwritten: {GENERATED}")

    if not args.submit:
        print("\nDry-run. Re-run with --submit to sbatch via phoenix-gw.")
        return

    submit_cmd = f"SLURM_CONF={SLURM_CONF} {SBATCH_BIN} {GENERATED}"
    res = subprocess.run(["ssh", SLURM_LOGIN_NODE, submit_cmd], capture_output=True, text=True)
    if res.returncode == 0:
        print(f"Submitted: {res.stdout.strip()}")
    else:
        print(f"ERROR: {res.stderr.strip()}")


if __name__ == "__main__":
    main()
