#!/usr/bin/env python
"""
SGD-nu' twin of sweep_train_al_3000cap.py.

IDENTICAL grid/mechanics to the 2026-06-11 sweep (train_al_3000cap_pcrand__20260611_131458),
the ONLY difference being the nu' values: this reads the **SGD** nu_prime estimates
instead of the Adam ones the original used.

Grid (90 jobs):
  strategies : probcover, random
  taus       : 0.1, 0.25, 0.5
  seeds      : 2, 3, 4
  (batch, nu'-cache budgets, max_iter):
     batch=100  -> nu' from budgets {100, 300, 1000}, max_iter=29
     batch=300  -> nu' from budget  {300},            max_iter=9
     batch=1000 -> nu' from budget  {1000},           max_iter=2

nu' source: results/cifar100/nu_prime_cache_optcompare.json  (key [strat]["sgd"][budget][tau]),
the consolidated 4-arm optimizer-comparison cache. Passed EXPLICITLY via --nu_prime so the
nu'-estimation budget is decoupled from --budget.

Distinct sweep-name prefix (train_al_3000cap_sgd__) and an "_sgd" exp-name suffix so the
SGD runs are cleanly comparable to / never collide with the original Adam runs.

Usage:
    python batch_utils/sweep_train_al_3000cap_sgd.py            # dry-run: print plan + script
    python batch_utils/sweep_train_al_3000cap_sgd.py --submit   # write .sh and sbatch via phoenix-gw
"""
from __future__ import annotations
import json, sys, subprocess, argparse
from pathlib import Path
from datetime import datetime

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sweep_train_al import (
    REPO_DIR, TRAIN_SCRIPT, LOG_DIR, VENV_ACTIVATE, SLURM_OPTS,
    SLURM_LOGIN_NODE, SBATCH_BIN, SLURM_CONF,
)

CACHE = REPO_DIR / "results" / "cifar100" / "nu_prime_cache_optcompare.json"
OPTIMIZER = "sgd"
CFG = "deep_al/configs/cifar100/al/RESNET18.yaml"
GENERATED = REPO_DIR / "batch_utils" / "_generated_sweep_train_al_3000cap_sgd.sh"
THROTTLE = 6

STRATEGIES = ["probcover", "random"]
TAUS = [0.1, 0.25, 0.5]
SEEDS = [2, 3, 4]
COMBOS = [  # (batch, nu'-cache budgets, max_iter)
    (100, [100, 300, 1000], 29),
    (300, [300], 9),
    (1000, [1000], 2),
]
TAU_KEY = {0.1: "0.1000", 0.25: "0.2500", 0.5: "0.5000"}


def build_jobs(sweep_name: str) -> list[str]:
    cache = json.load(open(CACHE))
    jobs = []
    for strat in STRATEGIES:
        for batch, nu_budgets, max_iter in COMBOS:
            for nu_b in nu_budgets:
                for tau in TAUS:
                    nu = cache[strat][OPTIMIZER][str(nu_b)][TAU_KEY[tau]]
                    for seed in SEEDS:
                        tau_s = str(tau).replace(".", "p")
                        exp = f"{strat}_B{batch}_nucache{nu_b}_tau{tau_s}_seed{seed}_{OPTIMIZER}"
                        cmd = (
                            f"python {TRAIN_SCRIPT} --initial_delta 0.75 --budget {batch} "
                            f"--eval_model_type from_features --max_iter {max_iter} "
                            f"--cfg {CFG} --tau {tau} --nu_prime {nu} --al {strat} --seed {seed} "
                            f"--exp-name {exp} --sweep-name {sweep_name} "
                            f"--track_progress --tag nu_tag={OPTIMIZER}_b{nu_b}"
                        )
                        jobs.append(cmd)
    return jobs


def build_script(jobs: list[str]) -> str:
    n = len(jobs)
    job_lines = "\n".join(f'JOBS[{i}]="{jobs[i]}"' for i in range(n))
    header = "\n".join(f"#SBATCH --{k}={v}" for k, v in SLURM_OPTS.items())
    return (
        f"#!/bin/bash\n"
        f"#SBATCH --array=0-{n - 1}%{THROTTLE}\n"
        f"{header}\n\n"
        f"# ---- job table (auto-generated by sweep_train_al_3000cap_sgd.py) ----\n"
        f"declare -A JOBS\n{job_lines}\n\n"
        f"CMD=${{JOBS[$SLURM_ARRAY_TASK_ID]}}\n"
        f'echo "Task $SLURM_ARRAY_TASK_ID: $CMD"\n\n'
        f"cd {REPO_DIR}\n"
        f"source {VENV_ACTIVATE}\n"
        f'eval "$CMD"\n'
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--submit", action="store_true",
                    help="Write the .sh and submit via sbatch on phoenix-gw")
    args = ap.parse_args()

    sweep_name = "train_al_3000cap_sgd__" + datetime.now().strftime("%Y%m%d_%H%M%S")
    jobs = build_jobs(sweep_name)

    print(f"sweep_name: {sweep_name}")
    print(f"nu' source: {CACHE.name} [strat][{OPTIMIZER}][budget][tau]")
    print(f"total jobs: {len(jobs)}  (array throttle %{THROTTLE})\n")
    print("first 3 + last 3 jobs:")
    for c in jobs[:3] + jobs[-3:]:
        print("  " + c.split(str(TRAIN_SCRIPT))[1].strip())

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(build_script(jobs))
    print(f"\nwritten: {GENERATED}")

    if not args.submit:
        print("\nDry-run. Re-run with --submit to sbatch via phoenix-gw.")
        return

    submit_cmd = f"SLURM_CONF={SLURM_CONF} {SBATCH_BIN} {GENERATED}"
    res = subprocess.run(["ssh", SLURM_LOGIN_NODE, submit_cmd], capture_output=True, text=True)
    if res.returncode == 0:
        print(f"Submitted: {res.stdout.strip()}")
    else:
        print(f"ERROR: {res.stderr.strip()}")


if __name__ == "__main__":
    main()
