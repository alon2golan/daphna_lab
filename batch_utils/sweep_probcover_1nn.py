"""
Launch the ProbCover + 1-NN evaluation arm for the §4 tables in
docs/bayesian_coverage_SUMMARY.md.

Motivation: the ProbCover paper's framework (ii) evaluates AL selection with a
1-NN classifier over the self-supervised (SimCLR) embedding instead of training
a network. daphna_lab already implements it (MODEL.USE_1NN -> sklearn
KNeighborsClassifier(n_neighbors=1), fitted on the labeled set's features each
episode). The original TypiClust repo never shipped this evaluator.

Grid — the exact like-for-like twin of the probcover arm in sweep 30978366:
  noise {0.0, 0.2, 0.5, 0.8} (one BAYESCOV_n*.yaml per level)
    x  al = probcover
    x  seed {1, 2, 3}
  = 12 runs.  budget 100/episode, 10 episodes -> 100..1000 labeled.

Only the evaluator differs from the existing probcover rows:
`--eval_model_type NN1` instead of `from_features`. Under noise the 1-NN fits
on the raw observed (noisy) labels, same as the probcover-with-training arm.

Sweep name carries the "BAYESCOV" token for dashboard auto-categorisation.
Mirrors sweep_bayes_coverage.py.

Usage:
    python batch_utils/sweep_probcover_1nn.py            # dry-run: print plan + script
    python batch_utils/sweep_probcover_1nn.py --submit   # write .sh and sbatch it
"""
import argparse
import subprocess
from datetime import datetime
from pathlib import Path

from sweep_train_al import (
    build_jobs_from,
    SLURM_OPTS,
    SLURM_LOGIN_NODE,
    SBATCH_BIN,
    SLURM_CONF,
    REPO_DIR,
    VENV_ACTIVATE,
    LOG_DIR,
)

CFG_DIR = "deep_al/configs/cifar100/al"
AL_CONFIGS = [
    f"--cfg {CFG_DIR}/BAYESCOV_n00.yaml --tag noise=0.0",
    f"--cfg {CFG_DIR}/BAYESCOV_n20.yaml --tag noise=0.2",
    f"--cfg {CFG_DIR}/BAYESCOV_n50.yaml --tag noise=0.5",
    f"--cfg {CFG_DIR}/BAYESCOV_n80.yaml --tag noise=0.8",
]
GRID = dict(
    al=["probcover"],
    seed=[1, 2, 3],
)
FIXED_ARGS = (
    "--track_progress "
    "--eval_model_type NN1 "   # <-- the only delta vs the existing probcover rows
    "--kernel_type tophat "
    "--budget 100 "
    "--initial_delta 0.75 "
    "--max_iter 9 "            # 100 -> 1000 labeled set (10 episodes)
)

ARRAY_THROTTLE = 6  # max concurrent array tasks (%N) — keep within group GPU quota
SWEEP_SCRIPT = Path(__file__).resolve().parent / "_probcover_1nn_sweep.sh"


def build_script(jobs, array_throttle):
    n = len(jobs)
    job_lines = "\n".join(f'JOBS[{i}]="{jobs[i]}"' for i in range(n))
    header_lines = "\n".join(f"#SBATCH --{k}={v}" for k, v in SLURM_OPTS.items())
    return (
        f"#!/bin/bash\n"
        f"#SBATCH --array=0-{n - 1}%{array_throttle}\n"
        f"{header_lines}\n"
        f"\n"
        f"# ---- job table (auto-generated by sweep_probcover_1nn.py) ----\n"
        f"declare -A JOBS\n"
        f"{job_lines}\n"
        f"\n"
        f"CMD=${{JOBS[$SLURM_ARRAY_TASK_ID]}}\n"
        f'echo "Task $SLURM_ARRAY_TASK_ID: $CMD"\n'
        f"\n"
        f"cd {REPO_DIR}\n"
        f"source {VENV_ACTIVATE}\n"
        f'eval "$CMD"\n'
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--submit", action="store_true",
                    help="Write the .sh and sbatch it via the SLURM login node.")
    args = ap.parse_args()

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    sweep_name = f"BAYESCOV_probcover1nn_cifar100_n0_20_50_80__{ts}"
    jobs = build_jobs_from(AL_CONFIGS, GRID, FIXED_ARGS, sweep_name=sweep_name)
    script = build_script(jobs, ARRAY_THROTTLE)

    print(f"Sweep name : {sweep_name}")
    print(f"Grid       : {GRID}")
    print(f"Fixed args : {FIXED_ARGS.strip()}")
    print(f"Total runs : {len(jobs)}  (array 0-{len(jobs) - 1}%{ARRAY_THROTTLE})\n")
    for j in jobs:
        print("  " + j.replace(str(REPO_DIR) + "/", ""))

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    SWEEP_SCRIPT.write_text(script)
    print(f"\nWritten: {SWEEP_SCRIPT}")

    if not args.submit:
        print("\nDry-run. Re-run with --submit to launch "
              "(CHECK GROUP GPU QUOTA FIRST — see daphna_lab/CLAUDE.md).")
        return

    submit_cmd = f"SLURM_CONF={SLURM_CONF} {SBATCH_BIN} {SWEEP_SCRIPT}"
    ssh_cmd = ["ssh", SLURM_LOGIN_NODE, submit_cmd]
    print(f"\nSubmitting: {' '.join(ssh_cmd)}")
    result = subprocess.run(ssh_cmd, capture_output=True, text=True)
    if result.returncode == 0:
        print(f"Submitted: {result.stdout.strip()}")
    else:
        print(f"ERROR (rc={result.returncode}): {result.stderr.strip()}")


if __name__ == "__main__":
    main()
